<?php
declare(strict_types=1);
session_start();
function h(string $s): string { return htmlspecialchars($s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'); }
$done = false; $error = ''; $success = '';
if (file_exists(__DIR__ . '/config.php')) {
    $error = 'config.php already exists. For safety, installer.php will not overwrite it. Delete installer.php after installation.';
} elseif ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $host = trim((string)($_POST['db_host'] ?? ''));
    $name = trim((string)($_POST['db_name'] ?? ''));
    $user = trim((string)($_POST['db_user'] ?? ''));
    $pass = (string)($_POST['db_pass'] ?? '');
    $title = trim((string)($_POST['board_title'] ?? 'QuietBoard'));
    $admin = trim((string)($_POST['admin_user'] ?? 'admin'));
    $adminPass = (string)($_POST['admin_pass'] ?? '');
    if (!$host || !$name || !$user || !$title || !$admin || strlen($adminPass) < 12) {
        $error = 'Fill in all fields. Admin password must be at least 12 characters.';
    } else {
        try {
            $pdo = new PDO("mysql:host={$host};dbname={$name};charset=utf8mb4", $user, $pass, [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                PDO::ATTR_EMULATE_PREPARES => false
            ]);
            $pdo->exec("CREATE TABLE IF NOT EXISTS threads (
                id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
                subject VARCHAR(120) NOT NULL,
                sticky TINYINT(1) NOT NULL DEFAULT 0,
                created_at DATETIME NOT NULL,
                bumped_at DATETIME NOT NULL,
                INDEX idx_threads_bump (bumped_at),
                INDEX idx_threads_sticky (sticky)
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");
            $pdo->exec("CREATE TABLE IF NOT EXISTS posts (
                id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
                thread_id BIGINT UNSIGNED NOT NULL,
                name VARCHAR(40) NOT NULL DEFAULT 'Anonymous',
                body TEXT NOT NULL,
                ip_address VARCHAR(45) NOT NULL,
                created_at DATETIME NOT NULL,
                INDEX idx_posts_thread (thread_id),
                INDEX idx_posts_ip (ip_address),
                CONSTRAINT fk_posts_threads FOREIGN KEY (thread_id) REFERENCES threads(id) ON DELETE CASCADE
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");
            $pdo->exec("CREATE TABLE IF NOT EXISTS admins (
                id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
                username VARCHAR(40) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");
            $pdo->exec("CREATE TABLE IF NOT EXISTS bans (
                id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
                ip_address VARCHAR(45) NOT NULL UNIQUE,
                reason VARCHAR(255) NOT NULL DEFAULT '',
                created_at DATETIME NOT NULL
            ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");
            $count = (int)$pdo->query('SELECT COUNT(*) FROM admins')->fetchColumn();
            if ($count > 0) throw new RuntimeException('An admin account already exists in this database. Use a fresh database or create the admin manually; installer did not reset credentials.');
            $stmt = $pdo->prepare('INSERT INTO admins (username, password_hash) VALUES (?, ?)');
            $stmt->execute([$admin, password_hash($adminPass, PASSWORD_DEFAULT)]);
            $config = "<?php\n// Generated by installer.php. Keep this file private.\ndefine('DB_HOST', " . var_export($host, true) . ");\ndefine('DB_NAME', " . var_export($name, true) . ");\ndefine('DB_USER', " . var_export($user, true) . ");\ndefine('DB_PASS', " . var_export($pass, true) . ");\ndefine('BOARD_TITLE', " . var_export($title, true) . ");\n";
            if (file_put_contents(__DIR__ . '/config.php', $config, LOCK_EX) === false) {
                throw new RuntimeException('Tables/admin were created, but PHP could not write config.php. Create it manually using config.sample.php and your values.');
            }
            $success = 'Installation complete. Sign in on index.php. Immediately delete installer.php from your hosting account.';
            $done = true;
        } catch (Throwable $e) {
            $error = 'Setup failed: ' . $e->getMessage() . ' Check the exact MySQL host, database name, username and password in your InfinityFree Control Panel.';
        }
    }
}
